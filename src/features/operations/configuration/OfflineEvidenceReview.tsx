import { useId, useRef, useState } from "react";
import { z } from "zod";
const reviewSchema = z.object({
  schema_version: z.literal("gridpulse-component-intake-review-v1"),
  dataset_id: z.string().max(200),
  capture_sha256: z.string().regex(/^[a-f0-9]{64}$/),
  quality_accepted: z.boolean(),
  blockers: z.array(z.string().max(300)).max(100),
  calibrated: z.literal(false),
  activated: z.literal(false),
  automatic_live_dispatch_authorized: z.literal(false),
});
/** Local report inspection only: this component has no upload or job submission path. */
export function OfflineEvidenceReview() {
  const [report, setReport] = useState<z.infer<typeof reviewSchema> | null>(
      null,
    ),
    [error, setError] = useState("");
  const sequence = useRef(0);
  const control = useRef<HTMLInputElement>(null);
  const helpId = useId();
  const [busy, setBusy] = useState(false);
  return (
    <section className="ops-offline-review" aria-label="Offline evidence review" aria-busy={busy}>
      <h3>Offline quality report</h3>
      <p>
        Review a quality report on this device. To add measurements to a plan,
        use the evidence-import controls.
      </p>
      <small id={helpId}>Choose a GridPulse quality review (.json), up to 16 MB. Raw captures need to be processed into a review report first. The selected report stays on this device.</small>
      <input
        ref={control}
        name="offline-quality-report"
        aria-describedby={helpId}
        type="file"
        accept=".json,application/json"
        aria-label="Offline quality report JSON"
        onChange={async (event) => {
          const ticket = ++sequence.current,
            file = event.currentTarget.files?.[0];
          setReport(null);
          setError("");
          setBusy(false);
          if (!file) return;
          setBusy(true);
          try {
            if (file.size > 16 * 1024 * 1024)
              throw new Error("Review exceeds 16 MB.");
            const parsed = reviewSchema.safeParse(JSON.parse(await file.text()));
            if (!parsed.success) throw new Error("Choose a GridPulse quality review JSON generated by the offline intake tool. This file has an unsupported format or approval state.");
            if (ticket === sequence.current) setReport(parsed.data);
          } catch (reason) {
            if (ticket === sequence.current)
              setError(
                reason instanceof SyntaxError ? "This file is not valid JSON. Select the generated review report and try again." : reason instanceof Error ? reason.message : "The report could not be read. Choose the file again.",
              );
          } finally {
            if (ticket === sequence.current) setBusy(false);
          }
        }}
      />
      <p role="status" className="ops-offline-status">{busy ? "Reading local report…" : report ? `Local report loaded. ${report.quality_accepted ? "Declared sample checks passed." : "Review the failed checks below."}` : "No local review report selected."}</p>
      {error ? <p role="alert">{error}</p> : null}
      {report ? (
        <>
          <p>Dataset: {report.dataset_id}</p>
          <p>
            Declared sample quality:{" "}
            {report.quality_accepted ? "checks passed" : "checks failed"}
          </p>
          <ul>
            {report.blockers.map((b) => (
              <li key={b}>{b.replaceAll("_", " ")}</li>
            ))}
          </ul>
          <p>Source authenticity and permission require independent review. Calibration and operational approval are still required.</p>
          <details><summary>Capture identity</summary><code translate="no">{report.capture_sha256}</code></details>
          <button
            type="button"
            className="secondary-button"
            onClick={() => {
              ++sequence.current;
              setReport(null);
              setError("");
              setBusy(false);
              if (control.current) { control.current.value = ""; control.current.focus(); }
            }}
          >
            Clear report
          </button>
        </>
      ) : null}
    </section>
  );
}
