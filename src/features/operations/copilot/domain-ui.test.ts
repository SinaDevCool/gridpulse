import { createElement } from "react";
import { guidanceSchema } from "./guidance-contracts";
import { it, expect, vi } from "vitest";
import { renderToStaticMarkup } from "react-dom/server";
import { GuidanceReferences } from "./GuidanceReferences";
import { PrivateAnalysisReview } from "./PrivateAnalysisReview";
import { retrieveOperationalKnowledge } from "../../../server/operations/operational-knowledge";
import { canonicalMilpJob } from "../../../../tests/fixtures/canonical-milp-job";
import { buildSyntheticMilpRequest } from "../synthetic-milp-request";
import { defaultOperationsScenario } from "../scenario-engine";
import { selectCanonicalPresentation } from "../canonical-presentation";
const mode = vi.hoisted(() => ({ public: false }));
vi.mock("../../../lib/public-milp-session", () => ({ publicMilpEnabled: () => mode.public }));
vi.mock("../../../lib/analytics-api", () => ({ listAnalyticsJobs: vi.fn(), startChronologicalShadow: vi.fn(), startFacilityUncertainty: vi.fn(), waitForAnalyticsJob: vi.fn() }));
it("keeps report applicability and exclusions while avoiding duplicate explanation text", () => {
  const guidance = guidanceSchema.parse(retrieveOperationalKnowledge("liquid cooling topology").find(item => "sourceId" in item && item.sourceId === "B04"));
  const html = renderToStaticMarkup(createElement(GuidanceReferences, { references: [guidance], describedIds: [guidance.id] }));
  const paragraph = renderToStaticMarkup(createElement("p", null, guidance.text));
  expect(html).not.toContain(paragraph);
  expect(renderToStaticMarkup(createElement(GuidanceReferences, { references: [guidance] }))).toContain(paragraph);
  expect(html).toContain("Excluded uses");
  expect(html).toContain("Evidence needed for site use");
  expect(html).toContain(".pdf#page=");
  expect(html).toContain(guidance.sourceContentHash!);
});
it("keeps private analysis gated and provides named decimal controls behind a disclosure", () => {
  const request = buildSyntheticMilpRequest(defaultOperationsScenario);
  const baseline = selectCanonicalPresentation(canonicalMilpJob(request), request);
  expect(renderToStaticMarkup(createElement(PrivateAnalysisReview, { baseline, enabled: false }))).toBe("");
  mode.public = true;
  expect(renderToStaticMarkup(createElement(PrivateAnalysisReview, { baseline, enabled: true }))).toBe("");
  mode.public = false;
  const html = renderToStaticMarkup(createElement(PrivateAnalysisReview, { baseline, enabled: true }));
  expect(html).toContain("Explore separate scenarios");
  expect(html).toContain('name="minimum-battery-temperature"');
  expect(html.match(/step="any"/g)).toHaveLength(3);
  expect(html).toContain("Minimum temperature must not exceed maximum");
  expect(html).not.toContain("<details open");
});
